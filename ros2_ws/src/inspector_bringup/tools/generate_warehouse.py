# Generate warehouse, ArUco marker models and ground-truth YAML

# Outputs: worlds/warehouse.sdf (Gazebo world),
#          models/aruco_marker_<id>/ (Gazebo model per marker),
#          config/warehouse_markers.yaml (marker ids + world poses),
#          model.config, model.sdf, materials/textures/aruco_<id>.png

import math
from pathlib import Path

import cv2
import numpy as np

PKG = Path(__file__).resolve().parents[1]  # inspector_bringup

# Layout parameters (metres and radians)
ROOM_X = 14.0          # warehouse length
ROOM_Y = 9.0           # warehouse width
WALL_T = 0.2           # wall thickness
WALL_H = 1.5           # wall height (taller than lidar)

SHELF_L = 1.8          # shelf length
SHELF_D = 0.6          # shelf depth
SHELF_H = 1.6          # shelf height

BASE_H = 0.4
ROW_Y = 1.2   
SHELF_X = [-3.6, -1.2, 1.2, 3.6]

# ArUco settings
ARUCO_DICT = cv2.aruco.DICT_4X4_50
MARKER_SIZE = 0.15 
PLATE_SIZE = 0.20
MARKER_Z = 0.22  
TEXTURE_PX = 512  

# Robot spawn pose
SPAWN = {'x': -6.0, 'y': 0.0, 'yaw': 0.0}


def box_model(name, x, y, z, sx, sy, sz, rgb, yaw=0.0, comment=None):
    """Return SDF for static box: one link with matching collision and visual"""
    r, g, b = rgb
    note = f'    <!-- {comment} -->\n' if comment else ''
    return f"""{note}    <model name="{name}">
      <static>true</static>
      <pose>{x:.3f} {y:.3f} {z:.3f} 0 0 {yaw:.4f}</pose>
      <link name="link">
        <collision name="collision">
          <geometry><box><size>{sx} {sy} {sz}</size></box></geometry>
        </collision>
        <visual name="visual">
          <geometry><box><size>{sx} {sy} {sz}</size></box></geometry>
          <material>
            <ambient>{r} {g} {b} 1</ambient>
            <diffuse>{r} {g} {b} 1</diffuse>
          </material>
        </visual>
      </link>
    </model>
"""


# Return SDF for 1 shelf unit: base cabinet, 4 posts, 3 boards. Each <link> part is a box positioned relative to shelf's origin
def shelf_model(name, x, y):  
    parts = []

    def part(pname, px, py, pz, sx, sy, sz, rgb):
        r, g, b = rgb
        parts.append(f"""        <collision name="{pname}_col">
          <pose>{px:.3f} {py:.3f} {pz:.3f} 0 0 0</pose>
          <geometry><box><size>{sx} {sy} {sz}</size></box></geometry>
        </collision>
        <visual name="{pname}_vis">
          <pose>{px:.3f} {py:.3f} {pz:.3f} 0 0 0</pose>
          <geometry><box><size>{sx} {sy} {sz}</size></box></geometry>
          <material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse></material>
        </visual>""")

    steel = (0.25, 0.35, 0.6)
    board = (0.85, 0.55, 0.2)  
    part('base', 0, 0, BASE_H / 2, SHELF_L, SHELF_D, BASE_H, steel)
    post = 0.05
    for i, (px, py) in enumerate([(1, 1), (1, -1), (-1, 1), (-1, -1)]):
        part(f'post{i}', px * (SHELF_L - post) / 2, py * (SHELF_D - post) / 2,
             SHELF_H / 2, post, post, SHELF_H, steel)
    for i, bz in enumerate([0.8, 1.2, SHELF_H - 0.01]):
        part(f'board{i}', 0, 0, bz, SHELF_L, SHELF_D, 0.02, board)

    body = '\n'.join(parts)
    return f"""    <model name="{name}">
      <static>true</static>
      <pose>{x:.3f} {y:.3f} 0 0 0 0</pose>
      <link name="link">
{body}
      </link>
    </model>
"""


# Render marker as a square PNG, 4 data cells + 1 border cell each side with white margin
def marker_texture(marker_id):
    dictionary = cv2.aruco.getPredefinedDictionary(ARUCO_DICT)
    inner_px = round(TEXTURE_PX * MARKER_SIZE / PLATE_SIZE)
    marker = cv2.aruco.generateImageMarker(dictionary, marker_id, inner_px)
    img = np.full((TEXTURE_PX, TEXTURE_PX), 255, dtype=np.uint8)
    off = (TEXTURE_PX - inner_px) // 2
    img[off:off + inner_px, off:off + inner_px] = marker
    return img


# Write marker model facing its local +x axis
def write_marker_model(marker_id):
    mdir = PKG / 'models' / f'aruco_marker_{marker_id}'
    tex_dir = mdir / 'materials' / 'textures'
    tex_dir.mkdir(parents=True, exist_ok=True)
    cv2.imwrite(str(tex_dir / f'aruco_{marker_id}.png'), marker_texture(marker_id))

    (mdir / 'model.config').write_text(f"""<?xml version="1.0"?>
<model>
  <name>aruco_marker_{marker_id}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>
    ArUco DICT_4X4_50 id {marker_id}, {MARKER_SIZE} m marker on a {PLATE_SIZE} m white plate.
    Generated by generate_warehouse.py.
  </description>
</model>
""")


    (mdir / 'model.sdf').write_text(f"""<?xml version="1.0"?>
<!-- Generated by generate_warehouse.py -->
<sdf version="1.9">
  <model name="aruco_marker_{marker_id}">
    <static>true</static>
    <link name="link">
      <!-- Marker is a sticker so shelf handles collisions -->
      <visual name="visual">
        <geometry><box><size>0.002 {PLATE_SIZE} {PLATE_SIZE}</size></box></geometry>
        <material>
          <ambient>1 1 1 1</ambient>
          <diffuse>1 1 1 1</diffuse>
          <specular>0 0 0 1</specular>
          <pbr>
            <metal>
              <albedo_map>model://aruco_marker_{marker_id}/materials/textures/aruco_{marker_id}.png</albedo_map>
              <roughness>1.0</roughness>
              <metalness>0.0</metalness>
            </metal>
          </pbr>
        </material>
      </visual>
    </link>
  </model>
</sdf>
""")


def main():
    half_x, half_y = ROOM_X / 2, ROOM_Y / 2
    models = []
    markers = []

    # --- Walls -------------------------------------------------------------
    wall_rgb = (0.75, 0.75, 0.72)
    models.append(box_model('wall_north', 0, half_y + WALL_T / 2, WALL_H / 2,
                            ROOM_X + 2 * WALL_T, WALL_T, WALL_H, wall_rgb,
                            comment='Outer walls: a closed room gives SLAM clean edges.'))
    models.append(box_model('wall_south', 0, -half_y - WALL_T / 2, WALL_H / 2,
                            ROOM_X + 2 * WALL_T, WALL_T, WALL_H, wall_rgb))
    models.append(box_model('wall_east', half_x + WALL_T / 2, 0, WALL_H / 2,
                            WALL_T, ROOM_Y, WALL_H, wall_rgb))
    models.append(box_model('wall_west', -half_x - WALL_T / 2, 0, WALL_H / 2,
                            WALL_T, ROOM_Y, WALL_H, wall_rgb))

    # --- Shelves and their markers -------------------------------------------
    # Each shelf gets two markers on base cabinet facing central and outer aisle
    # central aisle - 0-3: row A, 4-7: row B; Outer aisle - 8-11: row A, 12-15: row B
    shelves_yaml = []
    for row, sign in (('A', +1), ('B', -1)):
        for i, sx in enumerate(SHELF_X):
            name = f'shelf_{row}{i + 1}'
            sy = sign * ROW_Y
            models.append(shelf_model(name, sx, sy))
            row_idx = 0 if row == 'A' else 1
            for side, face_sign, base_id in (('aisle', -sign, 0), ('wall', +sign, 8)):
                mid = base_id + row_idx * 4 + i
                my = sy + face_sign * (SHELF_D / 2 + 0.001)
                myaw = math.pi / 2 if face_sign > 0 else -math.pi / 2
                markers.append((mid, sx, my, MARKER_Z, myaw))
                shelves_yaml.append((mid, name, side, sx, my, MARKER_Z, myaw))

    # Adding pieces to remove warehouse symmetry for lidar 
    models.append(box_model('pallet_stack_1', 5.9, -3.6, 0.35, 1.2, 1.0, 0.7, (0.6, 0.45, 0.3),
                            comment='Asymmetric clutter so AMCL can tell the two ends apart.'))
    models.append(box_model('pallet_stack_2', 5.9, -2.2, 0.25, 1.2, 1.0, 0.5, (0.6, 0.45, 0.3)))
    models.append(box_model('crate_1', -5.6, 3.7, 0.3, 0.6, 0.6, 0.6, (0.45, 0.35, 0.25)))
    models.append(box_model('pillar_1', 5.5, 2.8, 0.75, 0.3, 0.3, 1.5, (0.5, 0.5, 0.5)))
    models.append(box_model('pillar_2', -2.4, -3.3, 0.75, 0.3, 0.3, 1.5, (0.5, 0.5, 0.5)))

    for mid, mx, my, mz, myaw in markers:
        write_marker_model(mid)

    marker_includes = '\n'.join(
        f"""    <include>
      <uri>model://aruco_marker_{mid}</uri>
      <name>aruco_marker_{mid}</name>
      <pose>{mx:.3f} {my:.3f} {mz:.3f} 0 0 {myaw:.4f}</pose>
    </include>""" for mid, mx, my, mz, myaw in markers)

    world = f"""<?xml version="1.0"?>
<!--
  Warehouse generated by generate_warehouse.py

     +====================================================+  y = +4.5
     |  crate                                     pillar  |
     |        [A1]      [A2]      [A3]      [A4]          |  row A, y = +1.2
     |  R ->  ......... central aisle ...............     |  y = 0
     |        [B1]      [B2]      [B3]      [B4]   pallets|  row B, y = -1.2
     |                  pillar                     pallets|
     +====================================================+  y = -4.5
     x = -7                                           x = +7
-->
<sdf version="1.9">
  <world name="warehouse">

    <!-- 3 ms steps -->
    <physics name="3ms" type="ode">
      <max_step_size>0.003</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>

    <!-- "Systems" are Gazebo plugins that give the world its behaviour
         Sensors for lidar; Imu for IMU data; SceneBroadcaster for 3D window; UserCommands for tools like adding models while the sim runs. -->
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>

    <scene>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.8 0.85 0.9 1</background>
      <!-- Shadows not relevant -->
      <shadows>false</shadows>
    </scene>

    <!-- Overhead light -->
    <light type="directional" name="ceiling_light">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.1 0.1 0.1 1</specular>
      <direction>-0.3 0.2 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>30 30</size></plane></geometry>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>30 30</size></plane></geometry>
          <material>
            <ambient>0.55 0.55 0.55 1</ambient><diffuse>0.55 0.55 0.55 1</diffuse>
          </material>
        </visual>
      </link>
    </model>

{"".join(models)}
    <!-- Each <include> pulls models/aruco_marker_<id> -->
{marker_includes}

  </world>
</sdf>
"""
    (PKG / 'worlds').mkdir(exist_ok=True)
    (PKG / 'worlds' / 'warehouse.sdf').write_text(world)

    lines = [
        '# Ground truth for the warehouse world generated by generate_warehouse.py',
        '# Poses are in the Gazebo world frame (m, yaw in rad)',
        '# yaw is direction marker faces bot looks other directon to see it',
        "# map starts wherever the robot starts, so world shifted by spawn pose",
        'dictionary: DICT_4X4_50',
        f'marker_size_m: {MARKER_SIZE}',
        'spawn_pose:',
        f"  x: {SPAWN['x']}",
        f"  y: {SPAWN['y']}",
        f"  yaw: {SPAWN['yaw']}",
        'markers:',
    ]
    for mid, name, side, x, y, z, yaw in sorted(shelves_yaml):
        lines += [
            f'  - id: {mid}',
            f'    shelf: {name}',
            f'    side: {side}',
            f'    pose: {{x: {x:.3f}, y: {y:.3f}, z: {z:.3f}, yaw: {yaw:.4f}}}',
        ]
    (PKG / 'config').mkdir(exist_ok=True)
    (PKG / 'config' / 'warehouse_markers.yaml').write_text('\n'.join(lines) + '\n')
    print(f'Wrote world, {len(markers)} marker models and ground-truth YAML under {PKG}')


if __name__ == '__main__':
    main()
